#: A watermark configuration that is structurally valid and never used to score
#: anything here: every test in this file either stops before the detector or
#: replaces it. The tokenizer is deliberately a name nothing will fetch — a test
#: that reached the network would have stopped testing routing.
_WATERMARK = WatermarkConfig(ngram_len=5, keys=[1, 2, 3], tokenizer="test-tokenizer-never-loaded")

#: A page with no chatbot, no deep fake and no disclosure — the shape of target
#: that produced two useless warnings before this feature existed.
_STATIC_PAGE = (
    "Frisch gebrüht. Unsere Bäckerei backt seit 1932 nach überlieferten Rezepten. "
    "Öffnungszeiten: Montag bis Samstag von 6 bis 18 Uhr. Kontakt und Anfahrt."
)


