class TestUnverifiableObligations:
    """Issue #15 — the silent green this feature exists to close."""

    def test_undeclared_and_unconfigured_stays_a_skip(
        self,
        rulepack: Rulepack,
        patterns: dict[str, PatternSet],
        labels: dict[str, LabelPatternSet],
    ) -> None:
        """Nothing was promised, so nothing is owed."""
        evidence = make_evidence(make_turn("neutral-opener", "Hallo, hier spricht eine KI."))
        finding = _run(rulepack, evidence, patterns, labels)["MPF-T-001"]
        assert finding.result is Result.SKIP
