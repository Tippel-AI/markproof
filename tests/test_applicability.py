class TestScopeProseReadsAsEnglish:
    """Small thing, but this sentence is the first line an auditor reads."""

    @staticmethod
    def _summary(rulepack: Rulepack, declared: dict[str, bool]) -> str:
        return render_summary(
            build_report(
                target="t",
                rulepack=rulepack,
                findings=[],
                timestamp=_TIMESTAMP,
                applicability=Applicability.model_validate(declared),
            )
        )

    def test_one_excluded_obligation_stays_singular(self, rulepack: Rulepack) -> None:
        text = self._summary(rulepack, {"deepfake-labelling": False})
        assert "no `deepfake-labelling` obligation, so the rules serving it" in text

    def test_several_excluded_obligations_are_joined_and_pluralised(
        self, rulepack: Rulepack
    ) -> None:
        text = self._summary(rulepack, {"deepfake-labelling": False, "ai-interaction": False})
        assert "no `ai-interaction` or `deepfake-labelling` obligations" in text
        assert "the rules serving them" in text

    def test_several_included_obligations_agree_with_their_verb(self, rulepack: Rulepack) -> None:
        text = self._summary(
            rulepack, {"synthetic-text-marking": True, "synthetic-media-marking": True}
        )
        assert "`synthetic-media-marking` or `synthetic-text-marking` apply" in text, (
            "a list of obligations takes a plural verb"
        )
