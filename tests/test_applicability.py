"""Scope: which obligations bind a target, and what silence means.

The field test that produced these rules ran markproof against three pages
generated by a real product. Every one returned the same two warnings — no AI
disclosure, no deep fake label — and neither obligation bound any of them: the
pages have no chat interface and carry stock photography. Any static website on
earth gets those two lines. A tool that says the same thing about every target
says nothing, and it teaches its users that warnings are noise.

So a target can now declare what binds it. The tests here pin the three states
that declaration has, because the value of the feature lives entirely in keeping
them apart:

* **undeclared** — the rule runs, exactly as before. Silence must never remove
  a check, or an omission becomes an opt-out nobody made.
* **declared inapplicable** — SKIP, visibly, naming whose claim it was.
* **declared applicable but unverifiable** — WARN. "We mark our text", "nothing
  was checked" and a green build is the silent pass this project exists to
  remove.
"""

