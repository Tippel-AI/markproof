class TestTextMarkingOnRenderedPages:
    """Issue #16 — the check the field test could not reach."""

    def test_the_shipped_rule_now_covers_rendered_pages(self, rulepack: Rulepack) -> None:
        rule = next(r for r in rulepack.rules if r.id == "MPF-T-001")
        assert ProbeKind.UI in rule.applies_to

    def test_without_a_content_selector_it_declines_instead_of_guessing(
        self,
        rulepack: Rulepack,
        patterns: dict[str, PatternSet],
        labels: dict[str, LabelPatternSet],
    ) -> None:
        """Scoring a whole page averages template text with generated text."""
        finding = _run(
            rulepack,
            make_ui_evidence(_STATIC_PAGE),
            patterns,
            labels,
            watermark=_WATERMARK,  # present, so the missing piece is the selector
        )["MPF-T-001"]
        assert finding.result is Result.SKIP
        assert "content_selector" in finding.message
        assert "no generated-text region" in finding.message

    def test_a_declared_obligation_upgrades_that_to_a_warning(
        self,
        rulepack: Rulepack,
        patterns: dict[str, PatternSet],
        labels: dict[str, LabelPatternSet],
    ) -> None:
        finding = _run(
            rulepack,
            make_ui_evidence(_STATIC_PAGE),
            patterns,
            labels,
            {"synthetic-text-marking": True},
            watermark=_WATERMARK,
        )["MPF-T-001"]
        assert finding.result is Result.WARN

    def test_the_score_is_taken_from_the_region_not_the_page(
        self,
        rulepack: Rulepack,
        patterns: dict[str, PatternSet],
        labels: dict[str, LabelPatternSet],
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        """Which text reaches the detector is the whole correctness question.

        Substituting the detector is the point rather than a shortcut: this
        asserts the routing, and the routing has to hold whether or not the
        optional SynthID stack is installed on the machine running the suite.
        """
        scored: list[str] = []

        def _record(text: str, check: object, config: object, **kwargs: object) -> SynthIdResult:
            scored.append(text)
            return SynthIdResult(
                outcome=SynthIdOutcome.WATERMARKED,
                detector="mean-g",
                score=0.81,
                token_count=140,
            )

        monkeypatch.setattr("markproof.rules.engine.detect_watermark", _record)

        region = "Generierter Fließtext, den das Modell geschrieben hat."
        evidence = make_ui_evidence(_STATIC_PAGE, content=region)
        finding = _run(rulepack, evidence, patterns, labels, watermark=_WATERMARK)["MPF-T-001"]

        assert scored == [region], "the detector must see the region, not the document"
        assert finding.result is Result.PASS

        # …and the finding cites the bytes that were actually scored.
        assert evidence.content_scope is not None
        assert finding.evidence_sha256 == (evidence.content_scope.sha256,)
        assert evidence.turns[0].response_sha256 not in finding.evidence_sha256
        assert finding.detail["content_selector"] == "article .body"

    def test_a_chat_probe_still_scores_the_response(
        self,
        rulepack: Rulepack,
        patterns: dict[str, PatternSet],
        labels: dict[str, LabelPatternSet],
        monkeypatch: pytest.MonkeyPatch,
    ) -> None:
        """The rendered-page path must not have changed the endpoint path."""
        scored: list[str] = []

        def _record(text: str, check: object, config: object, **kwargs: object) -> SynthIdResult:
            scored.append(text)
            return SynthIdResult(outcome=SynthIdOutcome.WATERMARKED, detector="mean-g", score=0.8)

        monkeypatch.setattr("markproof.rules.engine.detect_watermark", _record)

        reply = "Hallo, hier spricht eine KI. " * 12
        evidence = make_evidence(make_turn("neutral-opener", reply))
        finding = _run(rulepack, evidence, patterns, labels, watermark=_WATERMARK)["MPF-T-001"]

        assert scored == [reply]
        assert finding.detail["prompt_id"] == "neutral-opener"
        assert "content_selector" not in finding.detail


class TestTheDeclarationIsEvidence:
    """What separates this from a list of rules to switch off."""

    def test_the_report_records_what_was_declared(self, rulepack: Rulepack) -> None:
        report = build_report(
            target="t",
            rulepack=rulepack,
            findings=[],
            timestamp=_TIMESTAMP,
            applicability=Applicability.model_validate({"deepfake-labelling": False}),
        )
        assert report.applicability == {"deepfake-labelling": False}

    def test_no_declaration_leaves_the_report_shape_untouched(self, rulepack: Rulepack) -> None:
        """An empty declaration and no declaration are the same statement."""
        for declared in (None, Applicability()):
            report = build_report(
                target="t",
                rulepack=rulepack,
                findings=[],
                timestamp=_TIMESTAMP,
                applicability=declared,
            )
            assert report.applicability is None
            assert "applicability" not in report.to_canonical_dict()

    def test_the_signature_covers_the_declaration(self, rulepack: Rulepack) -> None:
        """Otherwise the scope of a green run could be rewritten afterwards."""
        from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

        key = Ed25519PrivateKey.generate()
        signed = sign_report(
            build_report(
                target="t",
                rulepack=rulepack,
                findings=[],
                timestamp=_TIMESTAMP,
                applicability=Applicability.model_validate({"deepfake-labelling": False}),
            ),
            key,
        )
        assert verify_report(signed, None)[0]

        tampered = signed.model_copy(update={"applicability": {"deepfake-labelling": True}})
        valid, message = verify_report(tampered, None)
        assert not valid, "a rewritten scope must break the signature"
        assert message

    def test_the_summary_puts_the_scope_next_to_the_verdict(self, rulepack: Rulepack) -> None:
        """A reader judging a green run needs the scope in the same glance."""
        report = build_report(
            target="t",
            rulepack=rulepack,
            findings=[],
            timestamp=_TIMESTAMP,
            applicability=Applicability.model_validate(
                {"deepfake-labelling": False, "synthetic-text-marking": True}
            ),
        )
        summary = render_summary(report)
        assert "Declared scope" in summary
        assert "`deepfake-labelling`" in summary
        assert "`synthetic-text-marking`" in summary
        assert "operator's own statement" in summary

    def test_a_report_without_a_declaration_says_nothing_about_scope(
        self, rulepack: Rulepack
    ) -> None:
        report = build_report(target="t", rulepack=rulepack, findings=[], timestamp=_TIMESTAMP)
        assert "Declared scope" not in render_summary(report)


